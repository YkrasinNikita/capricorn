def match_route(cmd, routes=ROUTES):
    """Имя интента для фразы (первая подошедшая регулярка или плагин) или None.
    Без Win32-вызовов и без выполнения команд."""
    c = norm(cmd)
    for name, pattern, handler in routes:
        if re.search(pattern, c):
            return name
    from .plugins import load_plugins, match_plugin  # ленивый импорт: плагины не мешают ядру
    return match_plugin(c, load_plugins())
